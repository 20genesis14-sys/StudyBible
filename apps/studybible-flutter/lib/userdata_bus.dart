import 'package:flutter/foundation.dart';

/// Область извещения шины записей пользователя — координаты мутации,
/// если источник их знает. Все поля null — область не уточнена
/// («перечитать всё, что открыто»).
typedef UserDataScope = ({String? module, String? book, int? chapter});

/// Шина изменений записей пользователя (DECISIONS 18.10.2026, B8):
/// мутации извещают, ридер — первый подписчик; contributions
/// (ADR 0020) и будущие панели подпишутся так же.
///
/// Источник мутации (мост add/update/remove в библиотеке ридера)
/// вызывает [changed] один раз после пачки правок; подписчики сами
/// решают, касается ли их событие: экран чтения сверяет область
/// с открытой главой и коалицирует перечитки по кадру. Начальные
/// загрузки (открытие экрана, смена перевода/главы) шину не
/// проходят — это не мутации; история чтения (kind='hist') — тоже.
class UserDataBus extends ChangeNotifier {
  UserDataScope? _last;

  /// Область последнего извещения (null — извещение без области).
  UserDataScope? get lastScope => _last;

  /// Извещает подписчиков о мутации записей пользователя
  /// (добавление/правка/удаление). Координаты [module], [book],
  /// [chapter] источник заполняет, если знает; пачка правок одним
  /// жестом — одно извещение после всей пачки.
  void changed({String? module, String? book, int? chapter}) {
    _last = (module == null && book == null && chapter == null)
        ? null
        : (module: module, book: book, chapter: chapter);
    notifyListeners();
  }
}

/// Единственный на приложение экземпляр шины: источники мутаций
/// и подписчики (ридер, панели) живут в одном процессе.
final UserDataBus userDataBus = UserDataBus();
